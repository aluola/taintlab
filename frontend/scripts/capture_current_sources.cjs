/* Read-only production screenshot of the selected current-version real run. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { chromium } = require('../../scripts/browser_dependencies.cjs');
const root = path.resolve(__dirname, '../..');
const out = path.join(root, 'results/v2/browser');
const recordId = 'b727ecd1317c41711cd49c98';
const report = { captured_at: new Date().toISOString(), mode: 'read_only_real_replay', campaign: 'v2_baseline', record_id: recordId, errors: [], blocked_external: [] };
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, executablePath: require('../../scripts/browser_dependencies.cjs').executablePath() });
  const context = await browser.newContext({ viewport: { width: 1600, height: 900 }, locale: 'zh-CN' });
  await context.route('**/*', route => { const url = new URL(route.request().url()); if (url.origin === 'http://127.0.0.1:8501') return route.continue(); report.blocked_external.push(url.origin); return route.abort(); });
  const page = await context.newPage(); page.on('pageerror', error => report.errors.push(error.message));
  await page.goto('http://127.0.0.1:8501', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: '评测结果', exact: true }).click();
  await page.getByLabel('结果版本').selectOption('v2_baseline');
  await page.locator('.results-table').waitFor();
  await page.getByRole('textbox', { name: '筛选历史运行' }).fill('test_attack_direct_11 taint_policy 11');
  await page.locator('.replay-list button').first().waitFor();
  assert.equal(await page.locator('.replay-list button').count(), 1);
  await page.locator('.replay-list button').click(); await page.locator('.replay-banner').waitFor();
  assert.equal(await page.locator('.run-messages').getAttribute('data-run-id'), recordId);
  const run = await page.evaluate(async id => (await fetch(`/api/replays/v2_baseline/${id}`)).json(), recordId);
  assert.equal(run.version, '2.0.0'); assert.equal(run.backend_type, 'local_llama_cpp');
  const blocked = run.events.find(event => event.decision === 'block' && event.node_id);
  assert(blocked, 'This selected actual run must contain an auditable blocked action.');
  await page.getByRole('button', { name: '安全审计', exact: true }).click();
  await page.getByRole('tab', { name: '来源', exact: true }).click();
  await page.getByLabel('聚焦来源动作').selectOption(blocked.node_id);
  await page.getByRole('button', { name: '定位所选动作', exact: true }).click();
  assert((await page.locator('.drawer-run').textContent()).includes('2.0.0'));
  assert((await page.locator('.source-explanation').textContent()).includes('不能证明'));
  const file = path.join(out, 'focused-source-graph-v2.png');
  await page.screenshot({ path: file, animations: 'disabled' });
  report.version = run.version; report.backend_type = run.backend_type;
  report.selected_event = { step: blocked.step, tool: blocked.tool, decision: blocked.decision, reason: blocked.reason, node_id: blocked.node_id };
  report.visible_nodes = await page.locator('.source-card').count();
  report.screenshot = path.relative(root, file).replaceAll('\\', '/');
  report.sha256 = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  report.passed = true;
})().catch(error => { report.errors.push(String(error)); report.passed = false; process.exitCode = 1; }).finally(async () => {
  await browser?.close();
  fs.writeFileSync(path.join(out, 'focused-source-graph-v2.json'), JSON.stringify(report, null, 2), 'utf8');
  fs.writeFileSync(path.join(out, `focused-source-graph-v2_${report.captured_at.replace(/[:.]/g, '-')}.json`), JSON.stringify(report, null, 2), 'utf8');
  console.log(JSON.stringify(report, null, 2));
});
